export function tRel(lang, key) {
  return t(lang, `rel_${key}`);
}

export function tf(lang, key, vars = {}) {
  let text = t(lang, key);
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, value);
  }
  return text;
}
